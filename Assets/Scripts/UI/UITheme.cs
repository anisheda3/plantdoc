using System;
using TMPro;
using UnityEngine;

namespace PlantDoctor.UI
{
    /// <summary>
    /// The design tokens of the app, in one asset: colours, type, spacing, radii and motion.
    /// Every UI script reads from here, so the look can change without touching code.
    ///
    /// Botanical science: deep forest greens for the camera and AR experiences, warm ivory for
    /// everything you read, restrained gradients and line icons. Health is never shown by colour
    /// alone: every status also has a word and an icon.
    /// Sizes are canvas units for a 1080 x 2340 portrait reference.
    /// </summary>
    [CreateAssetMenu(menuName = "PlantDoctor/UI Theme", fileName = "UITheme")]
    public class UITheme : ScriptableObject
    {
        [Header("Brand greens")]
        public Color forest = Hex("#2F8F58");          // primary action green
        public Color forestDeep = Hex("#0A1B12");      // darkest surface (backdrop, camera, AR)
        public Color botanical = Hex("#62B77F");       // accent green for icons and active text
        public Color leaf = Hex("#A8D98A");            // fresh leaf green (highlights)
        public Color sage = Hex("#CFE3C8");            // pale sage
        public Color sageSoft = new Color(0.66f, 0.85f, 0.54f, 0.085f);   // soft green tint on glass

        [Header("Surfaces (dark glass over the plant backdrop)")]
        public Color ivory = new Color(0f, 0f, 0f, 0f);                    // page background: see-through, the backdrop shows
        public Color ivoryDeep = new Color(0.82f, 0.96f, 0.86f, 0.05f);            // sunken areas, tracks, inactive pills
        public Color white = new Color(0.80f, 0.96f, 0.85f, 0.034f);   // a faint green-tinted glass               // cards: frosted glass
        public Color divider = new Color(1f, 1f, 1f, 0.07f);
        public Color earth = Hex("#9A6847");
        public Color sheet = new Color(0.035f, 0.09f, 0.062f, 0.86f);     // the bottom sheet
        public Color backdropTop = Hex("#1B4A33");
        public Color backdropBottom = Hex("#071410");

        [Header("Status (always paired with text and an icon)")]
        public Color amber = Hex("#E9B24A");
        public Color amberSoft = new Color(0.91f, 0.70f, 0.29f, 0.10f);
        public Color red = Hex("#F0736A");
        public Color redSoft = new Color(0.94f, 0.45f, 0.42f, 0.10f);

        [Header("Text")]
        public Color textPrimary = Hex("#F4F1E6");
        public Color textSecondary = new Color(0.957f, 0.945f, 0.902f, 0.68f);
        public Color textTertiary = new Color(0.957f, 0.945f, 0.902f, 0.44f);
        public Color textOnDark = Hex("#F8F6EE");
        public Color textOnDarkMuted = new Color(0.97f, 0.96f, 0.92f, 0.74f);

        [Header("Translucent controls over camera / AR")]
        public Color glassDark = new Color(0.04f, 0.11f, 0.075f, 0.58f);
        public Color glassStroke = new Color(1f, 1f, 1f, 0.10f);
        public Color scrimDark = new Color(0.03f, 0.09f, 0.06f, 0.72f);

        [Header("Fonts (Inter, SIL OFL)")]
        public TMP_FontAsset fontRegular;
        public TMP_FontAsset fontMedium;
        public TMP_FontAsset fontSemiBold;
        public TMP_FontAsset fontBold;

        [Header("Type scale")]
        public float fontDisplay = 108f;
        public float fontH1 = 62f;
        public float fontH2 = 46f;
        public float fontH3 = 38f;
        public float fontBody = 33f;
        public float fontSmall = 29f;
        public float fontMeta = 26f;
        public float fontButton = 38f;

        [Header("Spacing and shape")]
        public float pagePadding = 48f;
        public float space = 24f;
        public float cardRadius = 38f;
        public float buttonRadius = 68f;
        public float buttonHeight = 128f;
        public float headerHeight = 150f;
        public float navHeight = 176f;
        public float touchMin = 108f;

        [Header("Motion")]
        public float screenFade = 0.28f;
        public float pressScale = 0.97f;

        [Header("Shapes (generated by UIShapeLibrary) and icons")]
        public Sprite roundedSprite;
        public Sprite outlineSprite;
        public Sprite circleSprite;
        public Sprite ringSprite;
        public Sprite softShadowSprite;
        public Sprite gradientSprite;
        public Sprite glowSprite;
        public Sprite arcSprite;
        public IconLibrary icons;

        /// <summary>Serif-free: every title is Inter Bold.</summary>
        public TMP_FontAsset TitleFont => fontBold != null ? fontBold : fontSemiBold;

        public const string ReducedMotionPref = "plantdoctor.reducedMotion";

        /// <summary>Animations shrink to instant changes when the user asked for reduced motion.</summary>
        public static bool ReducedMotion
        {
            get { try { return PlayerPrefs.GetInt(ReducedMotionPref, 0) == 1; } catch (Exception) { return false; } }
        }

        public Sprite Icon(string name) => icons != null ? icons.Get(name) : null;

        /// <summary>Tone for a severity value (lower is better): green, amber or red; always shown with a label too.</summary>
        public Color ToneForSeverity(float value01) =>
            value01 >= 0.55f ? red : value01 >= 0.25f ? amber : botanical;

        public Color SoftToneForSeverity(float value01) =>
            value01 >= 0.55f ? redSoft : value01 >= 0.25f ? amberSoft : sageSoft;

        public static string SeverityLabel(float value01) =>
            value01 >= 0.55f ? "Severe" : value01 >= 0.25f ? "Moderate" : "Mild";

        public static Color Hex(string hex)
        {
            ColorUtility.TryParseHtmlString(hex, out var c);
            return c;
        }

        public static string HexString(Color c) => ColorUtility.ToHtmlStringRGB(c);
    }
}
